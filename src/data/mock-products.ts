function createProduct(overrides: Partial<Product> & { id: string; name: string; slug: string; price: number }): Product {
  return {
    description: "",
    sku: `SKU-${overrides.id}`,
    currency: "BDT",
    images: [
      {
        id: "img-1",
        url: `/placeholder/${overrides.slug}.webp`,
        alt: overrides.name,
        width: 600,
        height: 600,
        isPrimary: true,
      },
    ],
    category: { id: "cat-1", slug: "components", name: "Components" },
    brand: { id: "brand-1", slug: "generic", name: "Generic" },
    specifications: [],
    inStock: true,
    tags: [],
    badges: [],
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    ...overrides,
  };
}

